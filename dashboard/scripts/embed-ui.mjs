import { gzipSync } from "node:zlib";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const dashboardDir = resolve(scriptDir, "..");
const distDir = resolve(dashboardDir, "dist");
const firmwareHeader = resolve(dashboardDir, "..", "firmware", "esp32", "IntelliRoomESP32", "dashboard_ui.h");

let html = readFileSync(resolve(distDir, "index.html"), "utf8");
html = html.replace(/<link rel="stylesheet" crossorigin href="([^"]+)">/, (_, assetPath) => {
  const css = readFileSync(resolve(distDir, assetPath.replace(/^\//, "")), "utf8");
  return `<style>${css}</style>`;
});
html = html.replace(/<script type="module" crossorigin src="([^"]+)"><\/script>/, (_, assetPath) => {
  const js = readFileSync(resolve(distDir, assetPath.replace(/^\//, "")), "utf8");
  return `<script type="module">${js}</script>`;
});

const compressed = gzipSync(Buffer.from(html), { level: 9 });
const bytes = Array.from(compressed, (value) => `0x${value.toString(16).padStart(2, "0")}`);
const lines = [];
for (let index = 0; index < bytes.length; index += 20) lines.push(`  ${bytes.slice(index, index + 20).join(", ")}`);

const header = `#pragma once

// Generated by dashboard/scripts/embed-ui.mjs. Do not edit this byte array by hand.
#include <Arduino.h>

constexpr size_t DASHBOARD_HTML_GZ_LEN = ${compressed.length};
const uint8_t DASHBOARD_HTML_GZ[] PROGMEM = {
${lines.join(",\n")}
};
`;

writeFileSync(firmwareHeader, header);
console.log(`Embedded ${html.length} bytes of HTML as ${compressed.length} bytes of gzip.`);
